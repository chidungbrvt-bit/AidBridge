package com.aidbridge.casefile.service;

import com.aidbridge.casefile.dto.response.EvidenceVersionResponse;
import com.aidbridge.casefile.entity.CaseEvidenceLink;
import com.aidbridge.casefile.entity.EvidenceFile;
import com.aidbridge.casefile.entity.EvidenceVersion;
import com.aidbridge.casefile.repository.CaseEvidenceLinkRepository;
import com.aidbridge.casefile.repository.EvidenceFileRepository;
import com.aidbridge.casefile.repository.EvidenceRepository;
import com.aidbridge.casefile.service.EvidenceFixtureCatalog.Fixture;
import com.aidbridge.shared.exception.BusinessException;
import java.util.List;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

@Service
@RequiredArgsConstructor
public class EvidenceService {
    private final EvidenceRepository evidence;
    private final EvidenceFileRepository files;
    private final CaseEvidenceLinkRepository evidenceLinks;

    @Transactional(propagation = Propagation.MANDATORY)
    public EvidenceVersionResponse append(UUID caseId, UUID orgId, UUID actorId, Fixture fixture,
            UUID fileId, UUID predecessorId, long nextCaseVersion) {
        if ((fileId == null) != (predecessorId == null)) throw BusinessException.invalid();

        EvidenceFile file;
        int versionNo = 1;
        if (fileId == null) {
            file = files.save(new EvidenceFile(caseId, orgId, actorId, fixture.title()));
        } else {
            var previous = evidence.scoped(predecessorId, List.of(orgId)).orElseThrow(BusinessException::missing);
            if (!caseId.equals(previous.caseId()) || !fileId.equals(previous.metadata().evidenceFileId())) {
                throw BusinessException.missing();
            }
            var links = evidenceLinks.findCurrent(caseId, orgId, predecessorId);
            if (links.isEmpty()) throw BusinessException.state();
            links.forEach(link -> link.retireAt(nextCaseVersion));
            versionNo = previous.metadata().versionNo() + 1;
            file = files.getReferenceById(fileId);
        }
        var version = evidence.save(new EvidenceVersion(file, caseId, orgId, actorId, versionNo,
                fixture.key(), fixture.hash(), fixture.bytes().length, predecessorId));
        // Flushing the link also fetches the version timestamp generated by the database.
        evidenceLinks.saveAndFlush(new CaseEvidenceLink(caseId, orgId, version, actorId));
        return EvidenceRepository.metadata(version);
    }
}
